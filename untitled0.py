def read_csv_robust(filename):
    actual_name = uploaded_names.get(filename.lower())

    if actual_name is None:
        raise FileNotFoundError(
            f"Missing {filename}. Upload all seven OULAD CSV files."
        )

    raw = uploaded[actual_name]

    # Try automatic delimiter detection first.
    try:
        df = pd.read_csv(
            io.BytesIO(raw),
            sep=None,
            engine="python"
        )
    except Exception:
        df = pd.read_csv(io.BytesIO(raw))

    # Normalize column names.
    df.columns = (
        df.columns.astype(str)
        .str.replace("\ufeff", "", regex=False)
        .str.strip()
        .str.lower()
        .str.replace(" ", "_", regex=False)
    )

    # Handle a common alternative name for course duration.
    if filename.lower() == "courses.csv":
        aliases = [
            "module_presentation_length",
            "presentation_length",
            "course_length",
            "duration"
        ]

        if "length" not in df.columns:
            for alias in aliases:
                if alias in df.columns:
                    df = df.rename(columns={alias: "length"})
                    print(
                        f"Renamed '{alias}' to 'length' in courses.csv"
                    )
                    break

    return df

